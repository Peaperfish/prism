// prism_profile: turns a LightCraft camera profile (JSON) into a matrix file for
// `prism --raw-camera-matrix`. See README, "Camera profiles".
//
//   prism_profile ILCE-7RM5.json -o samples/a7rv_lightcraft.txt --note "LightCraft PR #3022"
//
// Without -o the matrix file is written to stdout.

#include <array>
#include <cstdio>
#include <exception>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <optional>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

#include "prism/camera_profile.hpp"
#include "prism/version.hpp"

namespace {

void print_usage(const char* program) {
    std::cerr << "prism_profile " << prism::version()
              << " - convert a LightCraft camera profile to a Prism camera matrix\n"
              << "\n"
              << "Usage: " << program << " <profile.json> [-o <matrix.txt>] [--note <text>]\n"
              << "\n"
              << "Writes a white-balanced camera RGB -> linear sRGB (D65) matrix, rows summing to 1,\n"
              << "for prism --raw-camera-matrix. Without -o it goes to stdout.\n"
              << "--note adds a comment line to the file, e.g. which repository or commit the\n"
              << "profile came from (may be given several times).\n";
}

// One matrix row per line, aligned, with an optional prefix such as "#   ".
void write_rows(std::ostream& out, const prism::Mat3& m, std::string_view prefix) {
    out << std::fixed << std::setprecision(9);
    for (const auto& row : m) {
        out << prefix;
        for (int j = 0; j < 3; ++j) {
            out << (j ? " " : "") << std::setw(13) << row[j];
        }
        out << '\n';
    }
}

std::string matrix_file(const prism::LightCraftProfile& p, const std::string& source,
                        const std::vector<std::string>& notes, const prism::Mat3& srgb) {
    // Row sums of the unnormalised result, to show how far from white-preserving the fit was.
    const prism::Mat3 raw =
        prism::multiply(prism::xyz_to_srgb(), prism::multiply(prism::rec2020_to_xyz(), p.matrix));

    std::ostringstream out;
    out << "# White-balanced camera RGB -> linear sRGB (D65), for prism --raw-camera-matrix.\n"
        << "# Generated by prism_profile " << prism::version() << " from the LightCraft camera profile\n"
        << "#   " << source << "\n"
        << "#   model " << p.model << ", profile version " << p.version << ", fitted on " << p.files
        << " photos (" << p.samples << " colour pairs)\n";
    for (const std::string& note : notes) {
        out << "#   " << note << '\n';
    }
    out << "#\n"
        << "# LightCraft's matrix maps white-balanced camera RGB -> linear Rec. 2020:\n";
    write_rows(out, p.matrix, "#   ");
    out << "# Converted as normalize_rows(XYZ->sRGB * Rec2020->XYZ * matrix); both spaces are D65,\n"
        << "# so no chromatic adaptation. Row sums before normalising: " << std::setprecision(4)
        << raw[0][0] + raw[0][1] + raw[0][2] << ' ' << raw[1][0] + raw[1][1] + raw[1][2] << ' '
        << raw[2][0] + raw[2][1] + raw[2][2] << "\n"
        << "#\n"
        << "# The profile was fitted to the camera's own JPEGs, so this is a camera-JPEG look\n"
        << "# (more saturated, like the in-camera style), not a colorimetric calibration.\n";
    if (p.has_hue_sat) {
        out << "# Skipped: the profile's hue/saturation/value table (" << p.hue_divisions << "x"
            << p.sat_divisions << "x" << p.val_divisions
            << "), which a 3x3 matrix cannot represent.\n";
    }
    out << '\n';
    write_rows(out, srgb, "");
    return out.str();
}

}  // namespace

int main(int argc, char* argv[]) {
    const char* program = (argc > 0 && argv[0] != nullptr) ? argv[0] : "prism_profile";
    std::optional<std::string> input;
    std::optional<std::string> output;
    std::vector<std::string> notes;
    for (int i = 1; i < argc; ++i) {
        const std::string_view arg = argv[i];
        if (arg == "-h" || arg == "--help") {
            print_usage(program);
            return 0;
        }
        if (arg == "-o" && i + 1 < argc && !output) {
            output = argv[++i];
        } else if (arg == "--note" && i + 1 < argc) {
            notes.emplace_back(argv[++i]);
        } else if (!arg.starts_with('-') && !input) {
            input = std::string(arg);
        } else {
            std::cerr << "error: unexpected argument '" << arg << "'\n\n";
            print_usage(program);
            return 2;
        }
    }
    if (!input) {
        std::cerr << "error: no profile given\n\n";
        print_usage(program);
        return 2;
    }

    try {
        const prism::LightCraftProfile profile = prism::load_lightcraft_profile(*input);
        const prism::Mat3 srgb = prism::camera_to_srgb_from_rec2020(profile.matrix);
        const std::string text = matrix_file(profile, *input, notes, srgb);
        if (!output) {
            std::cout << text;
            return 0;
        }
        std::ofstream file(*output);
        if (!(file << text) || !file.flush()) {
            std::cerr << "error: cannot write '" << *output << "'\n";
            return 1;
        }
        std::cout << "wrote " << *output << " (" << profile.model << ", camera RGB -> linear sRGB):\n";
        write_rows(std::cout, srgb, "  ");
        if (profile.has_hue_sat) {
            std::cout << "skipped the hue/saturation/value table (not representable as a 3x3 matrix)\n";
        }
    } catch (const std::exception& e) {
        std::cerr << "error: " << e.what() << '\n';
        return 1;
    }
    return 0;
}
